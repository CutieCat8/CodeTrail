import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { emptyData, STORAGE_KEY } from "../../src/lib/storage";

test("bookmarks persist, transfer through export/import, and remove without learning credit", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/#curriculum");
  await page.getByText("ค้นหาและกรองบทเรียน", { exact: true }).click();
  const search = page.locator(".lesson-search");
  await search.getByLabel("บันทึกไว้", { exact: true }).check();
  await expect(search.locator("li")).toHaveCount(0);
  await search.getByLabel("บันทึกไว้", { exact: true }).uncheck();
  const first = search.locator("li").first();
  await first.getByRole("button", { name: /^บันทึกไว้เรียนภายหลัง:/ }).click();
  await search.getByLabel("บันทึกไว้", { exact: true }).check();
  await expect(search.locator("li")).toHaveCount(1);
  await first.getByRole("button", { name: /^เปิดบทเรียน/ }).click();
  const bookmark = page.getByRole("button", { name: /^บันทึกไว้เรียนภายหลัง:/ });
  await expect(bookmark).toHaveAttribute("aria-pressed", "true");
  await bookmark.click();
  await expect(bookmark).toHaveAttribute("aria-pressed", "false");
  await bookmark.click();
  await expect(bookmark).toHaveAttribute("aria-pressed", "true");
  await expect(page.locator(".save-pill")).toContainText("บันทึกแล้ว");
  await page.reload();
  await expect(bookmark).toHaveAttribute("aria-pressed", "true");
  const stored = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), STORAGE_KEY);
  expect(stored.stepProgress).toEqual({});
  expect(stored.progress).toEqual({});
  expect(stored.activityEvents).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  const accessibility = await new AxeBuilder({ page }).analyze();
  expect(accessibility.violations.filter(item => item.impact === "serious" || item.impact === "critical")).toEqual([]);
  await page.goto("/#settings");
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export JSON" }).click();
  const download = await downloadPromise;
  const path = await download.path();
  expect(path).toBeTruthy();
  await page.evaluate(({ key, data }) => localStorage.setItem(key, JSON.stringify(data)), { key: STORAGE_KEY, data: emptyData() });
  await page.reload();
  await page.getByLabel("เลือกไฟล์ JSON เพื่อนำเข้า").setInputFiles(path!);
  await expect(page.getByRole("status")).toContainText("นำเข้าข้อมูลสำเร็จ");
  await page.goto("/#curriculum");
  await page.getByText("ค้นหาและกรองบทเรียน", { exact: true }).click();
  await search.getByLabel("บันทึกไว้", { exact: true }).check();
  await expect(search.locator("li")).toHaveCount(1);
  await search.getByRole("button", { name: /^บันทึกไว้เรียนภายหลัง:/ }).click();
  await expect(search.locator("li")).toHaveCount(0);
  await expect.poll(async () => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).bookmarkedStepIds, STORAGE_KEY)).toEqual([]);
});
